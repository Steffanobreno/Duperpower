// Rebuilds src/lib/i18n/owner/keys.ts from the phrases the groomer's app uses. New phrases go at
// the end, so every language's list (same order) only needs new lines appended.
// Usage: node scripts/owner-keys.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { ownerPhrases } from "../tests/owner-phrases.mjs";

export const needsTranslation = (s) => /[A-Za-z]{2,}/.test(s.replace(/\{\w+\}/g, "")) && !/^<iframe/.test(s);
const file = "src/lib/i18n/owner/keys.ts";
const old = existsSync(file) ? JSON.parse(readFileSync(file, "utf8").match(/= (\[[\s\S]*\]);/)[1]) : [];
const used = [...ownerPhrases().keys()].filter(needsTranslation);
const keys = [...old, ...used.filter((k) => !old.includes(k))];
writeFileSync(file, `// The groomer's app phrases, in English. Each language file lists them in this same order.\n// Generated by scripts/owner-keys.mjs: new phrases are added at the end.\nexport const OWNER_KEYS: string[] = ${JSON.stringify(keys, null, 1)};\n`);
console.log(`${keys.length} phrases (${keys.length - old.length} new, ${keys.filter((k) => !used.includes(k)).length} no longer used)`);
