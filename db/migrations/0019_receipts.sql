-- Receipts. Every bill gets a short receipt number (#1001, #1002…) and a secret link the
-- client can open (/r/<token>) or get as a PDF. Receipts can also be written by hand for a
-- client (the receipt generator): those bills have no visit, so they keep their own times.
alter table invoices add column if not exists receipt_no int generated by default as identity (start with 1001);
alter table invoices add column if not exists public_token text unique default encode(gen_random_bytes(16), 'hex');
update invoices set public_token = encode(gen_random_bytes(16), 'hex') where public_token is null;
alter table invoices alter column public_token set not null;
alter table invoices add column if not exists checked_in_at timestamptz;   -- only for receipts without a visit
alter table invoices add column if not exists checked_out_at timestamptz;
alter table invoices add column if not exists receipt_emailed_at timestamptz;
